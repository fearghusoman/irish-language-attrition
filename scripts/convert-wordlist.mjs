#!/usr/bin/env node
// Converts the researcher-provided "FINAL 60 - Selected" sheet into:
//   1. app/src/data/wordlist.json   — bundled into the SPA, the runtime source of truth
//   2. supabase/seed_word_items.sql — INSERT statements for the DB-side word_items table
//
// Re-run this whenever the researcher hands over a new wordlist xlsx version.
// Both outputs are generated from the same parse so they can never drift apart.

import xlsx from "xlsx";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const __dirname = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = join(__dirname, "..");

const SOURCE_XLSX = join(REPO_ROOT, "context/irish-attrition-wordlist-template-v12.xlsx");
const SHEET_NAME = "FINAL 60 - Selected";
const WORDLIST_JSON_OUT = join(REPO_ROOT, "app/src/data/wordlist.json");
const SEED_SQL_OUT = join(REPO_ROOT, "supabase/seed_word_items.sql");

const CATEGORY_SLUGS = {
  "Concrete Noun": "concrete_noun",
  "Abstract Noun": "abstract_noun",
  Verb: "verb",
  Adjective: "adjective",
};

function splitGlossAlternatives(englishGloss) {
  return englishGloss.split("/").map((alt) => alt.trim());
}

function sqlQuote(value) {
  return `'${String(value).replace(/'/g, "''")}'`;
}

function sqlTextArray(values) {
  return `ARRAY[${values.map(sqlQuote).join(", ")}]::text[]`;
}

function main() {
  const workbook = xlsx.readFile(SOURCE_XLSX);
  const sheet = workbook.Sheets[SHEET_NAME];
  if (!sheet) {
    throw new Error(
      `Sheet "${SHEET_NAME}" not found. Available sheets: ${workbook.SheetNames.join(", ")}`
    );
  }

  const rows = xlsx.utils.sheet_to_json(sheet, { header: 1, raw: false, defval: "" });
  const [, ...dataRows] = rows; // drop header row

  const items = dataRows
    .filter((row) => row[0] !== "") // skip any blank trailing rows
    .map((row) => {
      const [idRaw, categoryRaw, englishGloss, irishTarget, freqRankRaw, familiarityRaw] = row;

      const category = CATEGORY_SLUGS[categoryRaw];
      if (!category) {
        throw new Error(`Unrecognized category "${categoryRaw}" for item ${idRaw}`);
      }

      return {
        item_id: Number(idRaw),
        category,
        irish_target: irishTarget,
        english_gloss: englishGloss,
        english_gloss_alternatives: splitGlossAlternatives(englishGloss),
        word_length: irishTarget.length,
        freq_rank: Number(freqRankRaw),
        familiarity_rating: familiarityRaw === "" ? null : Number(familiarityRaw),
      };
    })
    .sort((a, b) => a.item_id - b.item_id);

  if (items.length !== 60) {
    throw new Error(`Expected exactly 60 items, got ${items.length}`);
  }

  const perCategoryCounts = items.reduce((acc, item) => {
    acc[item.category] = (acc[item.category] ?? 0) + 1;
    return acc;
  }, {});
  for (const [category, count] of Object.entries(perCategoryCounts)) {
    if (count !== 15) {
      throw new Error(`Expected 15 items in category "${category}", got ${count}`);
    }
  }

  writeFileSync(WORDLIST_JSON_OUT, JSON.stringify(items, null, 2) + "\n");
  console.log(`Wrote ${items.length} items to ${WORDLIST_JSON_OUT}`);

  const seedSql = [
    "-- Auto-generated by scripts/convert-wordlist.mjs. Do not hand-edit.",
    "-- Run via the Supabase SQL editor (service_role context) — anon has no INSERT policy on word_items.",
    "",
    ...items.map(
      (item) =>
        `INSERT INTO word_items (item_id, category, irish_target, english_gloss, english_gloss_alternatives, word_length, freq_rank, familiarity_rating) VALUES ` +
        `(${item.item_id}, ${sqlQuote(item.category)}, ${sqlQuote(item.irish_target)}, ${sqlQuote(
          item.english_gloss
        )}, ${sqlTextArray(item.english_gloss_alternatives)}, ${item.word_length}, ${item.freq_rank}, ${
          item.familiarity_rating ?? "NULL"
        });`
    ),
    "",
  ].join("\n");

  writeFileSync(SEED_SQL_OUT, seedSql);
  console.log(`Wrote seed SQL to ${SEED_SQL_OUT}`);
}

main();
